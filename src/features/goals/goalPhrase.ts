// Ободряющая фраза под прогресс-баром цели (ТЗ п. 6.4) — всегда про сделанное, не про «осталось».
// В отличие от push-текстов (backend push_milestone_templates), это внутриэкранный, более лаконичный тон.
// Без эмодзи в тексте — иконка рисуется отдельно в GoalsProgress.tsx.
const LADDER: Record<number, string> = {
  5: 'Целых 5 дней заботы! Ты доказываешь себе, что готова к переменам.',
  10: '10 дней позади — забота о себе понемногу становится привычкой.',
  15: '15 дней! Чувствуешь, как внутри становится чуть спокойнее?',
  20: '20 дней заботы — ты заметно ближе к своей цели.',
  25: '25 дней рядом с собой. Твоя нежность к себе крепнет.',
  30: '30 дней — целый месяц заботы. Это по-настоящему много.',
  35: '35 дней! Ты держишь курс на себя, и это вдохновляет.',
  40: '40 дней заботы. Ты уже не та, что в начале пути.',
  45: '45 дней рядом с собой. Цель совсем близко.',
  50: '50 дней! Половина сотни тёплых шагов к себе.',
}

export function goalPhrase(count: number): string {
  if (count <= 0) return 'Сделай первый шаг — он самый важный.'
  if (count < 5) return 'Первый шаг сделан! Именно с него начинается путь к цели.'
  const step = Math.floor(count / 5) * 5
  return LADDER[step] ?? 'Ты прошла большой путь заботы о себе. Просто продолжай идти.'
}
