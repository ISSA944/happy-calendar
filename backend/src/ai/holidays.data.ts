/**
 * Возвращает праздник или wellness-тему дня.
 * Никогда не возвращает null — карточка должна быть видна КАЖДЫЙ день.
 *
 * @param date формат "DD.MM"
 */
export function resolveHoliday(date: string): HolidayEntry {
  const real = HOLIDAYS_FULL[date];
  if (real) return real;

  const floating = resolveFloatingHoliday(date);
  if (floating) return floating;

  const dayOfYear = computeDayOfYear(date);
  return WELLNESS_THEMES[dayOfYear % WELLNESS_THEMES.length];
}

// Плавающие праздники: День программиста, День отца, День матери
function resolveFloatingHoliday(date: string): HolidayEntry | null {
  const year = new Date().getFullYear();

  // День программиста — 256-й день года (13.09 в обычный год, 12.09 в високосный)
  const isLeap = (year % 4 === 0 && year % 100 !== 0) || year % 400 === 0;
  const progDate = isLeap ? '12.09' : '13.09';
  if (date === progDate) {
    return {
      name: 'День программиста',
      description: 'Код — это поэзия для машин.',
    };
  }

  // День отца — 3-е воскресенье октября
  if (date === getNthSunday(3, 10, year)) {
    return {
      name: 'День отца',
      description: 'Папа — первый герой в жизни каждого.',
    };
  }

  // День матери — последнее воскресенье ноября
  if (date === getLastSunday(11, year)) {
    return { name: 'День матери', description: 'Мама — самый важный человек.' };
  }

  return null;
}

function getNthSunday(n: number, month: number, year: number): string {
  let count = 0;
  for (let d = 1; d <= 31; d++) {
    const dt = new Date(year, month - 1, d);
    if (dt.getMonth() !== month - 1) break;
    if (dt.getDay() === 0) {
      count++;
      if (count === n) return fmt(d, month);
    }
  }
  return '';
}

function getLastSunday(month: number, year: number): string {
  let last = 0;
  for (let d = 1; d <= 31; d++) {
    const dt = new Date(year, month - 1, d);
    if (dt.getMonth() !== month - 1) break;
    if (dt.getDay() === 0) last = d;
  }
  return last ? fmt(last, month) : '';
}

function fmt(d: number, m: number): string {
  return `${String(d).padStart(2, '0')}.${String(m).padStart(2, '0')}`;
}

function computeDayOfYear(date: string): number {
  const [dayStr, monthStr] = date.split('.');
  const day = Number(dayStr);
  const month = Number(monthStr);
  if (!Number.isFinite(day) || !Number.isFinite(month)) return 0;
  const daysBeforeMonth = [
    0, 31, 59, 90, 120, 151, 181, 212, 243, 273, 304, 334,
  ];
  return (daysBeforeMonth[month - 1] ?? 0) + day;
}
