// 19 канонических тем фонов (ТЗ п. 7.4). Ключ — текст без эмодзи.
// Используется импорт-скриптом (нормализация колонки G xlsx) и API холидеев.
// Для праздников без готового WebP-пака картинки могут приходить из HolidayImage; иначе фронт рисует
// CSS-градиент по этому ключу (см. фронтовый THEME_GRADIENTS).

export const THEME_KEYS = [
  'Новый год и волшебство',
  'Зима и снег',
  'Весна и цветение',
  'Осень и уют',
  'Лето и море',
  'Космос и наука',
  'Животные и питомцы',
  'Еда и вкусности',
  'Спорт и движение',
  'Музыка, кино и искусство',
  'Путешествия и города',
  'Технологии и интернет',
  'Знания и образование',
  'Природа и планета',
  'Любовь, семья и дружба',
  'Забота о себе и спокойствие',
  'Красота и стиль',
  'Профессии и труд',
  'Уютные пустяки и радости',
] as const;

export type ThemeKey = (typeof THEME_KEYS)[number];

export const DEFAULT_THEME: ThemeKey = 'Уютные пустяки и радости';

const THEME_SET = new Set<string>(THEME_KEYS);

/**
 * Нормализует значение из колонки «Тема фона» xlsx (напр. "🎄 Новый год и волшебство")
 * к канонической теме без эмодзи. Неизвестное/пустое → дефолт «Уютные пустяки и радости».
 */
export function normalizeTheme(raw: string | null | undefined): ThemeKey {
  if (!raw) return DEFAULT_THEME;
  // Убираем всё до первой кириллической/латинской буквы (эмодзи, пробелы, спецсимволы).
  const cleaned = raw.replace(/^[^A-Za-zА-Яа-яЁё]+/, '').trim();
  return THEME_SET.has(cleaned) ? (cleaned as ThemeKey) : DEFAULT_THEME;
}
